#!/usr/bin/env python3
"""
assemble_manuscript.py — Builds 07_manuscript/full_manuscript.md.

Concatenates front_matter.md + part_1/*.md + part_2/*.md + part_3/*.md
(chapters sorted by filename within each part, README.md files
excluded) + back_matter.md into a single assembled file, with part
dividers inserted between parts.

Do not hand-edit 07_manuscript/full_manuscript.md directly — it is
regenerated by this script. Edit the individual front/back matter and
chapter files instead, then re-run this script.

Usage:
    python3 tools/assemble_manuscript.py

No third-party dependencies — standard library only.
"""

from __future__ import annotations

from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
MANUSCRIPT_DIR = REPO_ROOT / "07_manuscript"
OUTPUT_FILE = MANUSCRIPT_DIR / "full_manuscript.md"

PARTS = [
    ("part_1", "Part I — The Vacant Apartment"),
    ("part_2", "Part II — Seven Lives"),
    ("part_3", "Part III — The First Tenant"),
]


def read_if_real_content(path: Path) -> str:
    """Read a file's text, but return "" for not-yet-written placeholder
    stubs (identified by a `STATUS: EMPTY` or `STATUS: NOT STARTED`
    marker near the top, per this project's file-status convention) so
    the assembled manuscript doesn't include scaffolding boilerplate."""
    if not path.is_file():
        return ""
    text = path.read_text(encoding="utf-8").strip()
    header = "\n".join(text.splitlines()[:5])
    if "STATUS: EMPTY" in header or "STATUS: NOT STARTED" in header:
        return ""
    return text


def chapter_files(part_dir: Path) -> list[Path]:
    if not part_dir.is_dir():
        return []
    return sorted(
        p for p in part_dir.glob("*.md") if p.name.lower() != "readme.md"
    )


def main() -> int:
    sections: list[str] = []

    front = read_if_real_content(MANUSCRIPT_DIR / "front_matter.md")
    if front:
        sections.append(front)

    total_chapters = 0
    for slug, title in PARTS:
        part_dir = MANUSCRIPT_DIR / slug
        files = chapter_files(part_dir)
        if not files:
            continue
        sections.append(f"# {title}")
        for f in files:
            sections.append(f.read_text(encoding="utf-8").strip())
            total_chapters += 1

    back = read_if_real_content(MANUSCRIPT_DIR / "back_matter.md")
    if back:
        sections.append(back)

    if total_chapters == 0:
        print("No chapters found under 07_manuscript/part_*/ — nothing "
              "to assemble yet. See NEXT_ACTION.md.")
        return 0

    assembled = (
        "<!-- AUTO-GENERATED by tools/assemble_manuscript.py — "
        "do not hand-edit this file. Edit the source chapter files "
        "instead and re-run the script. -->\n\n"
        + "\n\n---\n\n".join(sections)
        + "\n"
    )
    OUTPUT_FILE.write_text(assembled, encoding="utf-8")
    print(f"Assembled {total_chapters} chapter(s) into "
          f"{OUTPUT_FILE.relative_to(REPO_ROOT)} "
          f"({len(assembled.split()):,} words).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
